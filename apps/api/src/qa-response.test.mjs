test("QA response cleaners preserve ordinary list, vector, set, and interval notation", () => {
  const cases = [
    "The list [1, 2, 3] has three numbers.",
    "The vector [-1, 0, 1] crosses zero.",
    "The matrix [[1, 2], [3, 4]] has two rows.",
    "The vector [1, 2] isn't empty.",
    "The teacher quoted 'alpha and beta' in prose.",
    "The variables [x', y'] are prime-marked.",
    "The variables [x'', y''] use repeated primes.",
    "The grouped terms [(x)', (y)'] carry primes.",
    "Compare [f'(x), g'(x)] in the derivative table.",
    "The set is {1, 2, 3}.",
    "Use [a, b] for the interval."
  ];

  for (const text of cases) {
    assert.equal(cleanQaResultForClient({ available: true, studentAnswer: text }).answer, text);
    const classroom = cleanClassroomQaResultForClient({
      qa: { available: true, studentAnswer: text },
      transcript: text,
      voice: { reason: text }
    });
    assert.equal(classroom.available, true);
    assert.equal(classroom.answer, text);
    assert.equal(classroom.transcript, text);
    assert.equal(classroom.voice.reason, text);
  }
});

test("cleanQaResultForClient caps answers and rejects structured internal content", () => {
  const longResult = cleanQaResultForClient({
    available: true,
    studentAnswer: "答".repeat(5000)
  });
  assert.equal(Array.from(longResult.answer).length, 2000);
  assert.equal(longResult.available, true);

  for (const studentAnswer of [
    '{"content":"safe","provider":"secret-provider"}',
    '回答前缀 {"content":"safe","raw":"secret-raw"} 回答后缀',
    "providerId: gpt56",
    "gpt56",
    ...terraSolInternalForms,
    ...lowercaseMinimaxInternalForms,
    ...structuredQaFragments,
    ...genericJsonFragments,
    ...unsafeSemanticArrays
  ]) {
    assert.deepEqual(cleanQaResultForClient({ available: true, studentAnswer }), {
      available: false,
      mode: "KNOWLEDGE_EXPLANATION",
      answer: "AI 问答暂时不可用，请稍后再试。"
    });
  }
});

