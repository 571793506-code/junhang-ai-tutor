test("cleanClassroomQaResultForClient validates voice values and caps visible text", () => {
  const result = cleanClassroomQaResultForClient({
    qa: { available: true, studentAnswer: "安全回答" },
    transcript: "问".repeat(2500),
    voice: {
      available: true,
      status: '{"status":"ready"}',
      audioUrl: "javascript:alert(1)",
      reason: "provider: secret-provider"
    }
  });

  assert.equal(Array.from(result.transcript).length, 2000);
  assert.deepEqual(result.voice, {
    available: true,
    status: null,
    audioUrl: null,
    reason: null
  });

  for (const reason of [
    "Generated by GPT-5.6",
    "Terra model unavailable",
    "Sol provider timeout",
    "OpenAI response failed",
    "DeepSeek response failed",
    "MiniMax speech unavailable",
    "providerId: gpt56",
    "gpt56",
    ...terraSolInternalForms,
    ...lowercaseMinimaxInternalForms
  ]) {
    const filtered = cleanClassroomQaResultForClient({
      qa: { available: true, studentAnswer: "安全回答" },
      voice: { reason }
    });
    assert.equal(filtered.voice.reason, null);
  }

  const longReason = cleanClassroomQaResultForClient({
    qa: { available: true, studentAnswer: "安全回答" },
    voice: { reason: "稍后重试".repeat(100) }
  }).voice.reason;
  assert.equal(Array.from(longReason).length, 240);
});

test("cleanClassroomQaResultForClient rejects bounded structured fragments in transcript and reason", () => {
  for (const fragment of [...structuredQaFragments, ...genericJsonFragments, ...unsafeSemanticArrays]) {
    const result = cleanClassroomQaResultForClient({
      qa: { available: true, studentAnswer: "安全回答" },
      transcript: fragment,
      voice: { reason: fragment }
    });
    assert.equal(result.transcript, "");
    assert.equal(result.voice.reason, null);
  }
});

test("cleanClassroomQaResultForClient allows only explicit statuses and safe audio URLs", () => {
  const allowedStatuses = [
    "ready",
    "queued",
    "pending",
    "processing",
    "completed",
    "failed",
    "unavailable",
    "error",
    "success"
  ];
  for (const status of allowedStatuses) {
    const result = cleanClassroomQaResultForClient({
      qa: { available: true, studentAnswer: "安全回答" },
      voice: { status }
    });
    assert.equal(result.voice.status, status);
  }
  for (const status of ["unknown", "READY", "{\"ready\":true}"]) {
    const result = cleanClassroomQaResultForClient({
      qa: { available: true, studentAnswer: "安全回答" },
      voice: { status }
    });
    assert.equal(result.voice.status, null);
  }

  for (const audioUrl of ["/generated/a.mp3", "http://example.com/a.mp3", "https://example.com/a.mp3"]) {
    const result = cleanClassroomQaResultForClient({
      qa: { available: true, studentAnswer: "安全回答" },
      voice: { audioUrl }
    });
    assert.equal(result.voice.audioUrl, audioUrl);
  }
  for (const audioUrl of [
    "//evil.example/a.mp3",
    "javascript:alert(1)",
    "data:audio/mp3;base64,AAAA",
    "file:///secret.mp3",
    "generated/a.mp3"
  ]) {
    const result = cleanClassroomQaResultForClient({
      qa: { available: true, studentAnswer: "安全回答" },
      voice: { audioUrl }
    });
    assert.equal(result.voice.audioUrl, null);
  }
});

test("QA routes use server-confirmed actor context and response cleaners", () => {
  const source = readFileSync(new URL("./server.js", import.meta.url), "utf8");
  const qaRoute = source.slice(
    source.indexOf('app.post("/api/ai/qa"'),
    source.indexOf('app.post("/api/ai/vocabulary"')
  );
  const classroomRoute = source.slice(
    source.indexOf('app.post("/api/classroom/voice-qa"'),
    source.indexOf('app.post("/api/classroom/reading"')
  );

  assert.match(qaRoute, /buildQaActorContext\(session, input,/);
  assert.match(qaRoute, /answerStudentQuestionService\(config, \{ \.\.\.input, \.\.\.actorContext \}, options\)/);
  assert.match(qaRoute, /cleanQaResultForClient\(result\)/);
  assert.match(classroomRoute, /assertClassroomStudentScope\(\{ session: req\.session \}, res, input\.studentId\)/);
  assert.doesNotMatch(classroomRoute, /prisma\.student\.findFirst/);
  assert.match(classroomRoute, /text: qa\.studentAnswer \|\| qa\.answer/);
  assert.match(classroomRoute, /cleanClassroomQaResultForClient/);
  const qaServiceIndex = classroomRoute.indexOf("const qa = await answerStudentQuestionService");
  const speechIndex = classroomRoute.indexOf("const speech = await createMiniMaxSpeechTask");
  assert.equal(qaServiceIndex >= 0 && speechIndex > qaServiceIndex, true);
});
